import SwiftUI

// MARK: - Shared state

@MainActor
@Observable
final class YatteeYPlayerExtras {
    static let shared = YatteeYPlayerExtras()
    private init() {}

    /// Comments float over the right side of the video.
    var showsCommentsOverlay = false

    /// The keyboard shortcut sheet over the video (? or ⌘/).
    var showsShortcuts = false

    private var environment: AppEnvironment { AppEnvironment.shared }
    private var player: PlayerService { environment.playerService }

    #if os(macOS)
    // MARK: Small window

    /// Details and comments are shown beside the video (big window).
    var isExpanded: Bool {
        environment.navigationCoordinator.isCornerLayoutActive
            && environment.settingsManager.landscapeDetailsPanelVisible
    }

    /// Toggles between the small video-only window and the big window with
    /// details below the video and comments on the right.
    func toggleDetails() {
        let settings = environment.settingsManager
        if isExpanded {
            settings.landscapeDetailsPanelVisible = false
            settings.landscapeDetailsPanelLastVisible = false
            if let ratio = player.state.videoAspectRatio, ratio > 0 {
                ExpandedPlayerWindowManager.shared.resizeToFitAspectRatio(ratio, animated: true)
            }
        } else {
            showsCommentsOverlay = false
            ExpandedPlayerWindowManager.shared.growForDetails()
            settings.landscapeDetailsPanelVisible = true
            settings.landscapeDetailsPanelLastVisible = true
        }
    }

    /// Comments float over the video only in the small window; in the big
    /// window the comments are already in the side column.
    func toggleComments() {
        if isExpanded {
            toggleDetails()
        } else {
            showsCommentsOverlay.toggle()
        }
    }
    #endif

    // MARK: Captions

    var captions: [Caption] { player.availableCaptions }
    var currentCaption: Caption? { player.currentCaption }

    /// The caption CC turns on: the last language picked, else Chinese, else
    /// the first manual track, else the first track.
    func preferredCaption() -> Caption? {
        let all = captions
        guard !all.isEmpty else { return nil }
        if let pref = environment.settingsManager.preferredSubtitlesLanguage, !pref.isEmpty {
            if let exact = Self.firstPreferringManual(all, where: { (c: Caption) -> Bool in c.languageCode == pref }) {
                return exact
            }
            let base: String = pref.split(separator: "-").first.map(String.init) ?? pref
            if let match = Self.firstPreferringManual(all, where: { (c: Caption) -> Bool in c.baseLanguageCode == base }) {
                return match
            }
        }
        if let zh = Self.firstPreferringManual(all, where: { (c: Caption) -> Bool in c.baseLanguageCode == "zh" }) {
            return zh
        }
        return Self.firstPreferringManual(all, where: { (_: Caption) -> Bool in true })
    }

    /// First caption matching `predicate`, preferring a manual track over an auto-generated one.
    private static func firstPreferringManual(_ captions: [Caption], where predicate: (Caption) -> Bool) -> Caption? {
        let matches: [Caption] = captions.filter(predicate)
        if let manual = matches.first(where: { (c: Caption) -> Bool in !c.isAutoGenerated }) {
            return manual
        }
        return matches.first
    }

    func toggleCaptions() {
        if currentCaption != nil {
            player.loadCaption(nil)
        } else if let caption = preferredCaption() {
            player.loadCaption(caption)
        }
    }

    func pick(_ caption: Caption) {
        player.loadCaption(caption)
        environment.settingsManager.preferredSubtitlesLanguage = caption.languageCode
    }

    // MARK: Quality

    /// Best stream per resolution, highest first. Hardware-decodable codecs
    /// win; software-only codecs show only when nothing else has that height.
    var qualityOptions: [Stream] {
        let candidates = player.availableStreams.filter { stream in
            guard !stream.isAudioOnly, !stream.url.isFileURL, stream.resolution != nil else { return false }
            let format = StreamFormat.detect(from: stream)
            return format != .hls && format != .dash
        }
        var best: [Int: Stream] = [:]
        for stream in candidates {
            let height = stream.resolution?.height ?? 0
            let priority = HardwareCapabilities.shared.codecPriority(for: stream.videoCodec)
            if let existing = best[height],
               HardwareCapabilities.shared.codecPriority(for: existing.videoCodec) >= priority {
                continue
            }
            best[height] = stream
        }
        return best.values.sorted { ($0.resolution?.height ?? 0) > ($1.resolution?.height ?? 0) }
    }

    var currentQualityLabel: String? {
        guard let stream = player.state.currentStream, !stream.isAudioOnly,
              let height = stream.resolution?.height else { return nil }
        return "\(height)p"
    }

    func select(_ stream: Stream) {
        let audio: Stream? = stream.isMuxed ? nil : (player.state.currentAudioStream ?? bestAudio())
        Task { await player.selectStreamManually(stream, audioStream: audio) }
    }

    private func bestAudio() -> Stream? {
        player.availableStreams.filter(\.isAudioOnly).max { ($0.bitrate ?? 0) < ($1.bitrate ?? 0) }
    }
}

#endif

#if os(macOS)

// MARK: - Control bar buttons (Mac)

/// "CC" toggles subtitles; the small chevron opens the language list.
struct YatteeYCaptionsButton: View {
    let size: CGFloat
    private let extras = YatteeYPlayerExtras.shared

    var body: some View {
        let isOn = extras.currentCaption != nil
        HStack(spacing: 0) {
            Button {
                extras.toggleCaptions()
            } label: {
                Image(systemName: isOn ? "captions.bubble.fill" : "captions.bubble")
                    .font(.system(size: size * 0.48, weight: .medium))
                    .foregroundStyle(isOn ? Color.accentColor : Color.primary)
                    .frame(width: size, height: size)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .help(isOn ? "关闭字幕（S）" : "打开字幕（S）")

            Menu {
                Button {
                    YatteeYPlayerExtras.shared.toggleCaptions()
                } label: {
                    if extras.currentCaption == nil { Label("关闭", systemImage: "checkmark") } else { Text("关闭") }
                }
                Divider()
                ForEach(extras.captions) { caption in
                    Button {
                        extras.pick(caption)
                    } label: {
                        let name = caption.displayName + (caption.isAutoGenerated ? "（自动）" : "")
                        if extras.currentCaption?.id == caption.id { Label(name, systemImage: "checkmark") } else { Text(name) }
                    }
                }
            } label: {
                Image(systemName: "chevron.down")
                    .font(.system(size: size * 0.28, weight: .semibold))
                    .foregroundStyle(.secondary)
                    .frame(width: size * 0.5, height: size)
                    .contentShape(Rectangle())
            }
            .menuStyle(.borderlessButton)
            .menuIndicator(.hidden)
            .fixedSize()
            .help("字幕语言")
        }
        .disabled(extras.captions.isEmpty)
        .opacity(extras.captions.isEmpty ? 0.4 : 1)
    }
}

/// Current quality ("1080p"); click for the list.
struct YatteeYQualityMenu: View {
    let size: CGFloat
    private let extras = YatteeYPlayerExtras.shared

    var body: some View {
        let options = extras.qualityOptions
        if let label = extras.currentQualityLabel, !options.isEmpty {
            Menu {
                ForEach(options, id: \.url) { stream in
                    Button {
                        extras.select(stream)
                    } label: {
                        let name = stream.resolution.map { "\($0.height)p" } ?? stream.qualityLabel
                        if name == label { Label(name, systemImage: "checkmark") } else { Text(name) }
                    }
                }
            } label: {
                HStack(spacing: 2) {
                    Text(label).font(.system(size: size * 0.4, weight: .semibold)).monospacedDigit()
                    Image(systemName: "chevron.down").font(.system(size: size * 0.26, weight: .semibold)).foregroundStyle(.secondary)
                }
                .frame(height: size)
                .padding(.horizontal, 4)
                .contentShape(Rectangle())
            }
            .menuStyle(.borderlessButton)
            .menuIndicator(.hidden)
            .fixedSize()
            .help("清晰度")
        }
    }
}

/// "详情" (small window ⇄ big window) and "评论" (comments over the video).
struct YatteeYPanelButtons: View {
    let size: CGFloat
    private let extras = YatteeYPlayerExtras.shared

    var body: some View {
        HStack(spacing: 2) {
            Button {
                extras.toggleComments()
            } label: {
                Image(systemName: extras.showsCommentsOverlay ? "text.bubble.fill" : "text.bubble")
                    .font(.system(size: size * 0.46, weight: .medium))
                    .foregroundStyle(extras.showsCommentsOverlay ? Color.accentColor : Color.primary)
                    .frame(width: size, height: size)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .help("评论（C）")

            Button {
                extras.toggleDetails()
            } label: {
                Image(systemName: extras.isExpanded ? "rectangle.inset.filled" : "rectangle.split.2x1")
                    .font(.system(size: size * 0.46, weight: .medium))
                    .frame(width: size, height: size)
                    .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .help(extras.isExpanded ? "只看视频（T）" : "展开详情和评论（T）")
        }
    }
}

// MARK: - Floating comments

/// Comments on a translucent panel over the right side of the video.
struct YatteeYCommentsOverlay: View {
    private let extras = YatteeYPlayerExtras.shared

    var body: some View {
        if extras.showsCommentsOverlay, let video = AppEnvironment.shared.playerService.state.currentVideo {
            GeometryReader { geometry in
                VStack(spacing: 0) {
                    HStack {
                        Text("评论").font(.headline)
                        Spacer()
                        Button {
                            extras.showsCommentsOverlay = false
                        } label: {
                            Image(systemName: "xmark").font(.system(size: 11, weight: .bold))
                        }
                        .buttonStyle(.plain)
                        .help("收起评论（Esc）")
                    }
                    .padding(.horizontal, 14)
                    .padding(.vertical, 10)

                    CommentsPanelPage(
                        context: PanelPageContext(appEnvironment: AppEnvironment.shared, video: video, accentColor: .accentColor),
                        scrollConfig: PanelScrollConfig(topInset: 0, bottomInset: 12)
                    )
                }
                .frame(width: max(260, geometry.size.width * 0.38))
                .frame(maxHeight: .infinity)
                .background(.ultraThinMaterial, in: RoundedRectangle(cornerRadius: 14))
                .environment(\.colorScheme, .dark)
                .padding(.top, 44)
                .padding(.bottom, 96)
                .padding(.trailing, 12)
                .frame(maxWidth: .infinity, alignment: .trailing)
            }
            .transition(.move(edge: .trailing).combined(with: .opacity))
        }
    }
}

